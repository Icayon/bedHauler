-- Fusionar offsets guardados en Config.TransporterVehicles
for modelHash, slots in pairs(_TM_Offsets) do
    if not Config.TransporterVehicles[modelHash] then
        Config.TransporterVehicles[modelHash] = { slots = {} }
    end
    for slotId, d in pairs(slots) do
        local applied = false
        for _, s in ipairs(Config.TransporterVehicles[modelHash].slots) do
            if s.id == slotId then
                s.offset     = vector3(d.ox, d.oy, d.oz)
                s.rotation   = vector3(d.rx, d.ry, d.rz)
                s.type       = d.t
                if d.dx then s.dropOffset = vector3(d.dx, d.dy, d.dz) end
                applied = true
                break
            end
        end
        if not applied then
            table.insert(Config.TransporterVehicles[modelHash].slots, {
                id         = slotId,
                type       = d.t,
                offset     = vector3(d.ox, d.oy, d.oz),
                rotation   = vector3(d.rx, d.ry, d.rz),
                dropOffset = d.dx and vector3(d.dx, d.dy, d.dz) or nil,
            })
        end
    end
